## บทที่ 1 · ทำไม CBO ต้องเริ่มคิดเรื่องกิจการเพื่อสังคม

ปี 2568 เป็นปีที่เขย่าองค์กรชุมชนด้านเอชไอวีทั่วโลก เมื่อรัฐบาลสหรัฐฯ ระงับและตัดงบ PEPFAR และ USAID อย่างกะทันหัน องค์กรจำนวนมากที่พึ่งพาเงินก้อนนี้เกือบทั้งหมดต้องปิดบริการลงภายในไม่กี่สัปดาห์ คำถามที่เคยดูเป็นเรื่องของอนาคต กลายเป็นเรื่องของวันนี้ทันที

### บทเรียนจากวิกฤตที่เพิ่งผ่านมา
ในฟิลิปปินส์ องค์กร LoveYourself รักษาคลินิกชุมชนทั้ง 22 แห่งให้เปิดต่อได้ตลอดช่วงที่งบสหรัฐฯ ถูกแช่แข็ง เพราะก่อนหน้านั้นเขาได้สร้างโมเดลที่ผูกกับระบบประกันสุขภาพแห่งชาติ (PhilHealth) และมีรายได้จากบริการระดับพรีเมียมมาอุดหนุนบริการฟรีไว้แล้ว ในขณะที่คลินิกของเครือข่ายเดียวกันอีกสิบแห่งที่พึ่งเงิน USAID อย่างเดียวต้องปิดตัว ความแตกต่างไม่ได้อยู่ที่ใครหาเงินบริจาคเก่งกว่า แต่อยู่ที่ใครสร้างฐานรายได้ที่หลากหลายและผูกกับระบบในประเทศไว้ก่อน

ที่ไทยเอง คลินิก Tangerine ของสถาบันเพื่อการวิจัยและนวัตกรรมด้านเอชไอวี (IHRI) ตอบโต้การตัดงบด้วยการเดินหน้าผลักดันเชิงนโยบายกับกระทรวงสาธารณสุขและ สปสช. จนได้งบประมาณฮอร์โมนบำบัดสำหรับคนข้ามเพศระดับชาติราว 145 ล้านบาทในเดือนมกราคม 2568 นี่คือบทพิสูจน์ว่าการมองงบประมาณภาครัฐเป็นโครงการความยั่งยืนหลัก ให้ผลตอบแทนสูงกว่าการวิ่งหาผู้บริจาครายใหม่ไปเรื่อย ๆ

**เรื่องของ SWING เอง** — SWING เดินทางมาไกลจากวันที่งบประมาณเกือบทั้งหมดมาจาก PEPFAR วันนี้ค่าใช้จ่ายในการดำเนินงานส่วนใหญ่มาจากการเบิกจ่ายของ สปสช. ซึ่งเป็นผู้สนับสนุนหลักในประเทศ การเปลี่ยนผ่านนี้สะท้อนความเติบโตขององค์กรอย่างแท้จริง แต่ก็เกิดความเสี่ยงรูปแบบใหม่ขึ้นมาแทน นั่นคือการพึ่งพาผู้จ่ายเงินรายเดียวอย่าง สปสช. มากเกินไป กิจการเพื่อสังคมจึงเข้ามาเติมเต็มช่องว่างตรงนี้ ด้วยการสร้างรายได้ที่ไม่มีเงื่อนไขผูกมัด ซึ่งเอาไปใช้ลงทุนกับนวัตกรรม งานรณรงค์ งานเข้าถึงประชากรที่ไม่มีสิทธิหลักประกันสุขภาพ และงานที่เงินภาครัฐไม่มีวันจ่ายให้

### กิจการเพื่อสังคมทำอะไรได้จริง และทำอะไรไม่ได้
ก่อนเริ่ม ต้องตั้งความคาดหวังให้ตรงความจริง ความเข้าใจผิดที่อันตรายที่สุดคือคิดว่ากิจการเพื่อสังคมจะมาแทนเงินบริจาคได้ทั้งหมด หลักฐานจากองค์กรที่ประสบความสำเร็จทั่วโลกบอกตรงกันว่า

- เครื่องมือยั่งยืนที่ใหญ่ที่สุดคือ **การเบิกจ่ายจากภาครัฐ** ไม่ใช่รายได้จากการค้า กิจการเพื่อสังคมเป็นชั้นรายได้ที่ยืดหยุ่นซ้อนอยู่ข้างบนอีกที
- เป้าหมายที่สมจริงของรายได้จากกิจการคือราว **20–30%** ของงบทั้งหมดเมื่อโตเต็มที่ ไม่ใช่ 70% แบบที่หลายองค์กรฝันไว้
- คุณค่าที่แท้จริงของกิจการหลายตัวอยู่ที่ **การจ้างงานและศักดิ์ศรีของชุมชน** ไม่ใช่ตัวกำไร โดยเฉพาะกิจการประเภทผลิตภัณฑ์และร้านอาหาร

อีกบทเรียนที่ต้องจำคือ องค์กรนำโดยชุมชนที่อยู่รอดยาวนานล้วนกระจายแหล่งทุนไม่ให้ผู้บริจาครายใดรายหนึ่งเกิน 30% และมีเงินสำรองอย่างน้อยหกเดือน คลินิก St James Infirmary ในซานฟรานซิสโกซึ่งเป็นคลินิกที่ดำเนินงานโดยพนักงานบริการและเป็นต้นแบบระดับโลก ปิดตัวในปี 2566 หลังเปิดมา 24 ปี ไม่ใช่เพราะวิกฤตเงินทุน แต่เพราะวิกฤตการบริหารและการเงินภายใน บทเรียนคือ การวางแผนสืบทอดตำแหน่ง การมีคนดูแลการเงินอย่างมืออาชีพ และการตั้งเงินสำรองอย่างระมัดระวัง ล้วนเป็นส่วนหนึ่งของภารกิจด้านสิทธิ ไม่ใช่เรื่องแยกต่างหาก

> **กล่องเครื่องมือ · แบบประเมินความเสี่ยงด้านการพึ่งพาผู้บริจาค (ทำเองได้ใน 10 นาที)**
> ตอบคำถามห้าข้อนี้กับทีมบริหาร ยิ่งตอบว่าใช่หลายข้อ ยิ่งต้องเริ่มวางแผนกิจการเพื่อสังคมโดยเร็ว
> 1. ผู้บริจาครายใหญ่ที่สุดของเราคิดเป็นเกิน 40% ของงบทั้งหมดหรือไม่
> 2. ถ้าผู้บริจาครายนั้นถอนตัวพรุ่งนี้ เราจะต้องปิดบริการภายในสามเดือนหรือไม่
> 3. เรามีเงินสำรองไม่ถึงหกเดือนของค่าใช้จ่ายดำเนินงานหรือไม่
> 4. รายได้ของเราเกือบทั้งหมดมาจากเงินโครงการที่มีเงื่อนไขผูกมัดว่าต้องใช้ทำอะไรหรือไม่
> 5. เราไม่มีรายได้ที่ไม่มีเงื่อนไข (unrestricted) ไว้ลงทุนสิ่งใหม่เลยหรือไม่
>
> **เกณฑ์อ่านผล:** ใช่ 0–1 ข้อ = มั่นคงพอควร แต่ควรเริ่มกระจายความเสี่ยง · ใช่ 2–3 ข้อ = มีความเสี่ยงต้องลงมือภายในปีนี้ · ใช่ 4–5 ข้อ = อยู่ในภาวะเปราะบาง ควรตั้งคณะทำงานด้านความยั่งยืนทันที

**ชวนคิด ชวนคุย**
- ถ้าวันนี้แหล่งทุนหลักของเราหายไป งานส่วนไหนที่เราจะไม่มีวันยอมให้หยุด และต้องใช้เงินเท่าไรต่อเดือนเพื่อประคองมันไว้
- ตอนนี้เรามีทรัพย์สินหรือทักษะอะไรอยู่แล้วบ้าง (พื้นที่ ความรู้ ความเชี่ยวชาญ ความไว้วางใจของชุมชน) ที่อาจแปลงเป็นรายได้ได้โดยไม่ทิ้งภารกิจ

