## เกี่ยวกับคู่มือเล่มนี้

คู่มือเล่มนี้เขียนขึ้นสำหรับองค์กรชุมชน (CBO) ขนาดเล็กที่กำลังเผชิญคำถามเดียวกับที่ SWING เคยเผชิญ นั่นคือ เมื่อเงินทุนจากผู้บริจาคต่างประเทศลดลงหรือหายไป องค์กรจะอยู่รอดและทำงานเพื่อชุมชนต่อไปได้อย่างไร

เราไม่ได้เขียนจากตำราเพียงอย่างเดียว แต่เขียนจากสิ่งที่ SWING ลงมือทำจริง ทั้งคลินิกชุมชน ร้านอาหารและเครื่องดื่มที่พัทยา แบรนด์ผลิตภัณฑ์ชุมชนอย่าง Million Charm งานฝึกอบรม บริการห้องปฏิบัติการ และแพลตฟอร์มสุขภาพดิจิทัล ทุกบทเรียนถูกร้อยเข้ากับตัวอย่างขององค์กรที่นำโดยชุมชนทั่วโลก ไม่ว่าจะเป็นพนักงานบริการ คนข้ามเพศ ผู้มีความหลากหลายทางเพศ หรือผู้อยู่ร่วมกับเอชไอวี เพื่อให้เห็นว่าแนวทางที่ได้ผลจริงหน้าตาเป็นอย่างไร และกับดักที่ทำให้องค์กรอื่นล้มเหลวคืออะไร

จุดยืนของเราชัดเจนตั้งแต่ต้น SWING เป็นองค์กรด้านสิทธิแรงงานและสิทธิพลเมืองของพนักงานบริการทุกเพศ สุขภาพเป็นผลพวงที่ตามมาจากการมีสิทธิและศักดิ์ศรี ไม่ใช่จุดเริ่มต้น คู่มือเล่มนี้จึงพูดเรื่องกิจการเพื่อสังคมในฐานะเครื่องมือปลดแอกทางเศรษฐกิจของชุมชน ไม่ใช่แค่ช่องทางหารายได้ และเราเชื่อว่ากิจการที่ดีต้องให้ชุมชนเป็นเจ้าของอย่างแท้จริง ทั้งในการบริหาร ค่าตอบแทน เสียงในการตัดสินใจ และสิทธิในการกำหนดว่าจะวัดความสำเร็จด้วยอะไร

### คู่มือนี้เหมาะกับใคร
- ผู้ก่อตั้งและผู้นำ CBO ที่อยากเริ่มทำกิจการเพื่อสร้างรายได้ที่ยืดหยุ่นและไม่ผูกกับเงื่อนไขผู้บริจาค
- ทีมงานองค์กรชุมชนด้านเอชไอวี สุขภาพทางเพศ สิทธิของกลุ่มประชากรหลัก และความหลากหลายทางเพศ
- เครือข่ายและพี่เลี้ยงที่ทำงานสนับสนุน CBO ให้เติบโตและยั่งยืน
- ผู้สนใจโมเดลความยั่งยืนแบบที่ให้ชุมชนเป็นศูนย์กลาง โดยไม่ทิ้งหลักการเรื่องสิทธิและศักดิ์ศรี

### วิธีใช้คู่มือ
คู่มือแบ่งเป็น **11 บท** เรียงจากเหตุผลว่าทำไมต้องเริ่ม ไปจนถึงแผนลงมือทำ 12 เดือน ทุกบทมีสามองค์ประกอบช่วยให้นำไปใช้ได้ทันที ได้แก่ **กล่องเครื่องมือ** ที่ให้เช็กลิสต์ ตาราง หรือแบบฟอร์มพร้อมใช้ · **กรณีศึกษา** ที่ยกตัวอย่างองค์กรจริง · และ **คำถามชวนคิดชวนคุย** ที่ทีมงานนำไปคุยกันต่อในวงประชุมได้ จะอ่านเรียงบทหรือกระโดดไปบทที่ต้องการก่อนก็ได้ แต่แนะนำให้อ่าน **บทที่ 4 และ 5** เรื่องโครงสร้างกฎหมายและการเงินภาครัฐก่อนตัดสินใจลงทุน เพราะเป็นรากฐานที่ตัดสินความอยู่รอดมากกว่าตัวกิจการเอง

